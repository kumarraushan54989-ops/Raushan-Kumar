package com.example.data

import com.example.base.FirestoreEmulatorTestBase
import com.example.model.DeliveryAddress
import com.example.model.OrderStatus
import com.google.firebase.firestore.FirebaseFirestoreException
import kotlinx.coroutines.flow.first
import kotlinx.coroutines.runBlocking
import kotlinx.coroutines.withTimeout
import org.junit.Assert.assertEquals
import org.junit.Assert.assertTrue
import org.junit.Assert.fail
import org.junit.Test

class QuickKartRepositoryRuleTest : FirestoreEmulatorTestBase() {

  @Test
  fun addToCart_andPlaceOrder_succeedsForOwnerAndClearsCart() = runBlocking {
    val uid = signInTestUser(ALICE_EMAIL)
    val repo = QuickKartRepository(firestore, auth)
    val product = CatalogData.curatedProducts.first()

    withTimeout(DEFAULT_TIMEOUT_MS) {
      repo.ensureUserProfile("Alice", ALICE_EMAIL, "9876543210")
      repo.addToCart(product, 1L)
    }

    val cartItems = withTimeout(FLOW_TIMEOUT_MS) {
      repo.observeCart(uid).first { it.any { item -> item.productId == product.id } }
    }
    assertEquals(1, cartItems.size)

    val address = DeliveryAddress(
      userId = uid,
      label = "Home",
      recipientName = "Alice",
      phone = "9876543210",
      streetAddress = "42 MG Road",
      city = "Bengaluru",
      pincode = "560038",
      latitude = 12.9784,
      longitude = 77.6408,
      isDefault = true
    )

    val addressId = withTimeout(DEFAULT_TIMEOUT_MS) { repo.saveAddress(address) }
    assertTrue(addressId.isNotBlank())

    val savedAddresses = withTimeout(FLOW_TIMEOUT_MS) {
      repo.observeAddresses(uid).first { it.any { a -> a.id == addressId } }
    }
    assertTrue(savedAddresses.first { it.id == addressId }.isDefault)

    val orderId = withTimeout(DEFAULT_TIMEOUT_MS) {
      repo.placeOrder(
        cartItems = cartItems,
        address = address,
        paymentMethod = "UPI",
        deliverySpeed = "EXPRESS",
        couponCode = "QUICK10",
        subtotal = product.price,
        discount = 1000L,
        deliveryFee = 0L,
        totalAmount = (product.price - 1000L).coerceAtLeast(1L)
      )
    }
    assertTrue(orderId.isNotBlank())

    val orders = withTimeout(FLOW_TIMEOUT_MS) {
      repo.observeOrders(uid).first { list -> list.any { it.id == orderId } }
    }
    assertEquals("PLACED", orders.first { it.id == orderId }.status)

    val lineItems = withTimeout(FLOW_TIMEOUT_MS) {
      repo.observeOrderItems(uid, orderId).first { it.isNotEmpty() }
    }
    assertEquals(product.id, lineItems.first().productId)

    withTimeout(DEFAULT_TIMEOUT_MS) {
      repo.updateOrderStatus(orderId, OrderStatus.DELIVERED)
    }
    val updatedOrder = withTimeout(FLOW_TIMEOUT_MS) {
      repo.observeOrderById(uid, orderId).first { it?.status == OrderStatus.DELIVERED.key }
    }
    assertEquals(OrderStatus.DELIVERED.key, updatedOrder?.status)
  }

  @Test
  fun observeCart_crossUserAccess_failsWithPermissionDenied() = runBlocking {
    val aliceUid = signInTestUser(ALICE_EMAIL)
    val aliceRepo = QuickKartRepository(firestore, auth)
    withTimeout(DEFAULT_TIMEOUT_MS) {
      aliceRepo.addToCart(CatalogData.curatedProducts.first(), 1L)
    }

    signInTestUser(BOB_EMAIL)
    val bobRepo = QuickKartRepository(firestore, auth)
    try {
      withTimeout(FLOW_TIMEOUT_MS) {
        bobRepo.observeCart(aliceUid).first()
      }
      fail("Expected PERMISSION_DENIED for cross-user cart observation")
    } catch (e: Exception) {
      val firestoreEx = e.unwrapFirestoreException()
      assertEquals(FirebaseFirestoreException.Code.PERMISSION_DENIED, firestoreEx?.code)
    }
  }

