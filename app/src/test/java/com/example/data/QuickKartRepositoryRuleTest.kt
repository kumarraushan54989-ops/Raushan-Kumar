  }

  @Test
  fun seedAndAddProduct_autoGeneratesIdAndStreamsForOwner() = runBlocking {
    val uid = signInTestUser(ALICE_EMAIL)
    val repo = QuickKartRepository(firestore, auth)

    withTimeout(DEFAULT_TIMEOUT_MS) {
      repo.seedStarterProductsIfEmpty()
    }

    val seeded = withTimeout(FLOW_TIMEOUT_MS) {
      repo.observeProducts(uid).first { it.isNotEmpty() }
    }
    assertTrue(seeded.any { it.id == CatalogData.curatedProducts.first().id })

    val autoGeneratedId = withTimeout(DEFAULT_TIMEOUT_MS) {
      repo.addProduct(
        com.example.model.Product(
          id = "",
          title = "Seller Wireless Mouse",
          brand = "ClickPro",
          categoryName = "Electronics",
          price = 799L,
          mrp = 1499L,
          rating = 4.5,
          reviewCount = 12L,
          highlights = listOf("Silent Clicks", "2.4GHz USB"),
          description = "Compact wireless mouse",
          badge = "Seller Pick",
          imageKey = "electronics",
          photoBase64 = "dGVzdF9waG90b19iYXNlNjQ=",
          deliveryDays = 1L,
          inStock = true,
          sellerListed = true
        )
      )
    }
    assertTrue(autoGeneratedId.isNotBlank())

    val updatedList = withTimeout(FLOW_TIMEOUT_MS) {
      repo.observeProducts(uid).first { list -> list.any { it.id == autoGeneratedId } }
    }
    val added = updatedList.first { it.id == autoGeneratedId }
    assertEquals("Seller Wireless Mouse", added.title)
    assertEquals("dGVzdF9waG90b19iYXNlNjQ=", added.photoBase64)
    assertEquals(uid, added.userId)

    withTimeout(DEFAULT_TIMEOUT_MS) {
      repo.updateProductPricingAndStock(
        autoGeneratedId,
        price = 649L,
        mrp = 1499L,
        inStock = false,
        photoBase64 = "dXBkYXRlZF9waG90bw=="
      )
    }
    val repricedList = withTimeout(FLOW_TIMEOUT_MS) {
      repo.observeProducts(uid).first { list ->
        list.firstOrNull { it.id == autoGeneratedId }?.price == 649L
      }
    }
    val repriced = repricedList.first { it.id == autoGeneratedId }
    assertEquals(649L, repriced.price)
    assertEquals(false, repriced.inStock)
    assertEquals("dXBkYXRlZF9waG90bw==", repriced.photoBase64)
  }

